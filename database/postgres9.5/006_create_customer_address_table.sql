-- Schema Migration: Create CUSTOMER_ADDRESS table for multiple addresses per customer
CREATE TABLE IF NOT EXISTS CUSTOMER_ADDRESS (
    ID SERIAL PRIMARY KEY,
    CUSTOMER_ID INTEGER REFERENCES CUSTOMER(AUTO_ID) ON DELETE CASCADE,
    ADDRESS_LABEL VARCHAR(60),
    ADDRESS_TEXT VARCHAR(620),
    ISDEFAULT BOOLEAN DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_customer_address_customer_id ON CUSTOMER_ADDRESS(CUSTOMER_ID);

-- Migrate existing CUSTOMER.ADDRESS into CUSTOMER_ADDRESS if not already present
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'customer_address') THEN
        INSERT INTO CUSTOMER_ADDRESS (CUSTOMER_ID, ADDRESS_LABEL, ADDRESS_TEXT, ISDEFAULT)
        SELECT c.AUTO_ID, 'Principal', c.ADDRESS, TRUE
        FROM CUSTOMER c
        WHERE c.ADDRESS IS NOT NULL AND TRIM(c.ADDRESS) <> ''
          AND NOT EXISTS (
              SELECT 1 FROM CUSTOMER_ADDRESS ca WHERE ca.CUSTOMER_ID = c.AUTO_ID
          );
    END IF;
END $$;
